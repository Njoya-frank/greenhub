create table if not exists public.support_presence (
  id integer primary key default 1 check (id = 1),
  is_available boolean not null default false,
  updated_at timestamptz not null default now()
);

insert into public.support_presence (id, is_available)
values (1, false)
on conflict (id) do nothing;

create table if not exists public.support_conversations (
  id uuid primary key default gen_random_uuid(),
  visitor_token text not null,
  customer_name text,
  customer_email text,
  status text not null default 'open' check (status in ('open', 'closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.support_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.support_conversations(id) on delete cascade,
  sender_type text not null check (sender_type in ('customer', 'bot', 'admin')),
  sender_id uuid references auth.users(id) on delete set null,
  sender_name text not null default 'Greenhub',
  body text not null check (length(trim(body)) > 0),
  created_at timestamptz not null default now()
);

create index if not exists support_conversations_updated_at_idx
  on public.support_conversations(updated_at desc);
create index if not exists support_messages_conversation_id_idx
  on public.support_messages(conversation_id, created_at);

create or replace function public.touch_support_conversation()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.support_conversations
  set updated_at = now()
  where id = new.conversation_id;
  return new;
end;
$$;

drop trigger if exists support_message_updates_conversation on public.support_messages;
create trigger support_message_updates_conversation
  after insert on public.support_messages
  for each row execute procedure public.touch_support_conversation();

create or replace function public.create_support_conversation(p_visitor_token text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare conversation_id uuid;
begin
  if length(trim(coalesce(p_visitor_token, ''))) < 24 then
    raise exception 'A valid visitor token is required';
  end if;

  insert into public.support_conversations (visitor_token)
  values (trim(p_visitor_token))
  returning id into conversation_id;

  return conversation_id;
end;
$$;

create or replace function public.get_support_messages(p_conversation_id uuid, p_visitor_token text)
returns setof public.support_messages
language sql
security definer
set search_path = public
as $$
  select messages.*
  from public.support_messages messages
  join public.support_conversations conversations on conversations.id = messages.conversation_id
  where conversations.id = p_conversation_id
    and conversations.visitor_token = trim(p_visitor_token)
  order by messages.created_at asc, messages.id asc;
$$;

create or replace function public.send_support_customer_message(p_conversation_id uuid, p_visitor_token text, p_body text)
returns public.support_messages
language plpgsql
security definer
set search_path = public
as $$
declare message public.support_messages;
begin
  if not exists (
    select 1
    from public.support_conversations
    where id = p_conversation_id
      and visitor_token = trim(p_visitor_token)
      and status = 'open'
  ) then
    raise exception 'Support conversation not found';
  end if;

  insert into public.support_messages (conversation_id, sender_type, sender_name, body)
  values (p_conversation_id, 'customer', 'You', trim(p_body))
  returning * into message;

  return message;
end;
$$;

create or replace function public.send_support_bot_message(p_conversation_id uuid, p_visitor_token text, p_body text)
returns public.support_messages
language plpgsql
security definer
set search_path = public
as $$
declare message public.support_messages;
begin
  if not exists (
    select 1
    from public.support_conversations
    where id = p_conversation_id
      and visitor_token = trim(p_visitor_token)
      and status = 'open'
  ) then
    raise exception 'Support conversation not found';
  end if;

  insert into public.support_messages (conversation_id, sender_type, sender_name, body)
  values (p_conversation_id, 'bot', 'Greenhub assistant', trim(p_body))
  returning * into message;

  return message;
end;
$$;

alter table public.support_presence enable row level security;
alter table public.support_conversations enable row level security;
alter table public.support_messages enable row level security;

drop policy if exists "Public can view support presence" on public.support_presence;
drop policy if exists "Admins manage support presence" on public.support_presence;
drop policy if exists "Admins manage support conversations" on public.support_conversations;
drop policy if exists "Admins manage support messages" on public.support_messages;

create policy "Public can view support presence" on public.support_presence
  for select using (true);
create policy "Admins manage support presence" on public.support_presence
  for all using (public.is_admin()) with check (public.is_admin());
create policy "Admins manage support conversations" on public.support_conversations
  for all using (public.is_admin()) with check (public.is_admin());
create policy "Admins manage support messages" on public.support_messages
  for all using (public.is_admin()) with check (public.is_admin());

grant select on public.support_presence to anon, authenticated;
grant select, insert, update, delete on public.support_presence, public.support_conversations, public.support_messages to authenticated;
grant execute on function public.create_support_conversation(text) to anon, authenticated;
grant execute on function public.get_support_messages(uuid, text) to anon, authenticated;
grant execute on function public.send_support_customer_message(uuid, text, text) to anon, authenticated;
grant execute on function public.send_support_bot_message(uuid, text, text) to anon, authenticated;
