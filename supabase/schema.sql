values (
  'greenhub',
  'greenhub',
  true,
  5242880,
  array['image/jpeg', 'image/png', 'image/webp', 'image/gif', 'image/avif']::text[]
)
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Admins manage Greenhub images" on storage.objects;
drop policy if exists "Greenhub admins can upload" on storage.objects;
drop policy if exists "Greenhub admins can read metadata" on storage.objects;
drop policy if exists "Greenhub admins can update" on storage.objects;
drop policy if exists "Greenhub admins can delete" on storage.objects;

create policy "Greenhub admins can upload" on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'greenhub'
    and public.is_admin()
    and (storage.foldername(name))[1] in ('products', 'storefront')
  );

create policy "Greenhub admins can read metadata" on storage.objects
  for select to authenticated
  using (
    bucket_id = 'greenhub'
    and public.is_admin()
    and (storage.foldername(name))[1] in ('products', 'storefront')
  );

create policy "Greenhub admins can update" on storage.objects
  for update to authenticated
  using (
    bucket_id = 'greenhub'
    and public.is_admin()
    and (storage.foldername(name))[1] in ('products', 'storefront')
  )
  with check (
    bucket_id = 'greenhub'
    and public.is_admin()
    and (storage.foldername(name))[1] in ('products', 'storefront')
  );

create policy "Greenhub admins can delete" on storage.objects
  for delete to authenticated
  using (
    bucket_id = 'greenhub'
    and public.is_admin()
    and (storage.foldername(name))[1] in ('products', 'storefront')
  );

